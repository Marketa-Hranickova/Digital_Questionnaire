"""REDCap clients: an in-memory mock for development and the real API client.

Both expose the same two methods, so switching is only REDCAP_MODE=mock|redcap.
Field names match the data dictionary generated by tools/fhir_to_redcap.py.
"""
import json

import httpx

MAIN_FORM = "vfq_questionnaire"
APPENDIX_FORM = "vfq_appendix"


class RedcapError(Exception):
    pass


def to_record(pid, answers, complete, include_appendix):
    """FHIR answers -> one flat REDCap record."""
    record = {"record_id": pid}
    for link_id, code in answers.items():
        record[link_id.lower().replace("-", "_")] = code
    # REDCap form status: 2 = Complete, 1 = Unverified
    status = "2" if complete else "1"
    record[f"{MAIN_FORM}_complete"] = status
    if include_appendix:
        record[f"{APPENDIX_FORM}_complete"] = status
    return record


class MockRedcap:
    """Keeps records in memory. Never use with real patient data."""

    def __init__(self):
        self.records = {}

    def import_record(self, record):
        self.records[record["record_id"]] = dict(record)
        return 1

    def export_pdf(self, pid):
        if pid not in self.records:
            raise RedcapError("record not found")
        return _mock_pdf(pid)


def _mock_pdf(pid):
    """Valid one-page placeholder PDF, so viewers can open it while testing the download flow."""
    stream = (f"BT /F1 18 Tf 72 760 Td (MOCK VFQ-25 record {pid}) Tj 0 -28 Td /F1 11 Tf "
              "(Placeholder from the mock server, not the REDCap PDF.) Tj ET").encode()
    objs = [b"<</Type/Catalog/Pages 2 0 R>>",
            b"<</Type/Pages/Count 1/Kids[3 0 R]>>",
            b"<</Type/Page/Parent 2 0 R/MediaBox[0 0 595 842]"
            b"/Resources<</Font<</F1 4 0 R>>>>/Contents 5 0 R>>",
            b"<</Type/Font/Subtype/Type1/BaseFont/Helvetica>>",
            b"<</Length %d>>stream\n" % len(stream) + stream + b"\nendstream"]
    out, offsets = b"%PDF-1.4\n", []
    for i, body in enumerate(objs, 1):
        offsets.append(len(out))
        out += b"%d 0 obj\n" % i + body + b"\nendobj\n"
    xref = len(out)  # byte offset of the cross-reference table
    out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(objs) + 1)
    out += b"".join(b"%010d 00000 n \n" % o for o in offsets)
    out += b"trailer<</Size %d/Root 1 0 R>>\nstartxref\n%d\n%%%%EOF\n" % (len(objs) + 1, xref)
    return out


class RealRedcap:
    """Calls the REDCap API. The token never leaves this server."""

    def __init__(self, api_url, token, timeout=20.0):
        self._url = api_url
        self._token = token
        # verify=True: always validate the REDCap server's TLS certificate
        self._client = httpx.Client(timeout=timeout, verify=True)

    def _post(self, data):
        payload = {"token": self._token, "returnFormat": "json", **data}
        try:
            r = self._client.post(self._url, data=payload)
        except httpx.HTTPError as e:
            raise RedcapError(f"REDCap not reachable: {type(e).__name__}") from None
        if r.status_code != 200:
            # REDCap error bodies can echo input; do not pass them on to the client
            raise RedcapError(f"REDCap returned HTTP {r.status_code}")
        return r

    def import_record(self, record):
        r = self._post({
            "content": "record",
            "action": "import",
            "format": "json",
            "type": "flat",
            "overwriteBehavior": "normal",
            "forceAutoNumber": "false",
            "returnContent": "count",
            "data": json.dumps([record]),
        })
        count = r.json().get("count")
        if count != 1:
            raise RedcapError("REDCap did not store the record")
        return count

    def export_pdf(self, pid):
        r = self._post({"content": "pdf", "record": pid, "instrument": MAIN_FORM})
        if not r.content.startswith(b"%PDF"):
            raise RedcapError("REDCap did not return a PDF")
        return r.content
